#1- Arithmetic Operators
num1 = 40
num2 = 8

print(num1 - num2) #Subtraction
print(num1 * num2) # Multiplication


#2- Assignment Operators

Value = 50
print(Value)

Value -= 10       #Subtract & assign
print(Value)

# #3. Comparison Operators
p1 = 12
p2 = 18
print(p1 < p2)            #less than comparison

p3 = 30
p4 = 25
print(p3 > p4)              #greater than comparison

#4. Logical Operators
x1 = 5
x2 = 15
x3 = 25
x4 = 35

print("And result :",x1 < x2 and x3 < x4) #AND condition
print("OR result :",x1 > x2 or x3 > x4) #OR condition

# # 5. Identity Operator
m1 = 100
m2 = 100
print(m1 is m2)

#6 . Membership Operators
print("check 'e' in ' mango' :", 'e' in 'mango')

